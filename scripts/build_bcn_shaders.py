#!/usr/bin/env python3
"""Compile the pinned Granite/BCn shaders into an embedded, aligned C++ header."""
from pathlib import Path
import os, struct, subprocess, tempfile
root = Path(__file__).resolve().parents[1]
source = root / 'app/libraries/bcn_shaders'
parts = ['// Generated by scripts/build_bcn_shaders.py; shader licenses in app/libraries/bcn_shaders.\n#pragma once\n#include <cstdint>\nnamespace skyline::gpu::bcn_shaders {\n']
with tempfile.TemporaryDirectory() as temp:
    for name in ('s3tc', 'bc6', 'bc7'):
        output = Path(temp) / (name + '.spv')
        subprocess.run([os.environ.get('GLSLC', 'glslc'), '-fshader-stage=compute', '-O', '-I' + str(source), str(source / (name + '.comp')), '-o', str(output)], check=True)
        data = output.read_bytes()
        words = struct.unpack('<' + 'I' * (len(data) // 4), data)
        parts.append('inline constexpr uint32_t ' + name + '[] = {\n')
        for i in range(0, len(words), 8):
            parts.append(','.join(hex(word) for word in words[i:i+8]) + ',\n')
        parts.append('};\n')
parts.append('}\n')
(root / 'app/src/main/cpp/skyline/gpu/texture/bcn_shaders.h').write_text(''.join(parts))
